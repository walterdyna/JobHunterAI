const fs = require("fs");
const path = require("path");
const Database = require("better-sqlite3");
const env = require("./environment");
const isPostgres = env.db.client === "postgres";

if (!["sqlite", "postgres"].includes(env.db.client)) {
  throw new Error("DB_CLIENT deve ser sqlite ou postgres.");
}

if (isPostgres && !env.db.connectionString) {
  throw new Error("DATABASE_URL obrigatória quando DB_CLIENT=postgres.");
}

const dbDir = path.join(__dirname, "..", "..", "database");
let db;
let pool;

const sqliteSchema = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS companies (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    name TEXT NOT NULL,
    city TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS vacancies (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    salary REAL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS applications (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    salary REAL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Pendente',
    platform TEXT,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS candidate_documents (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    kind TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_type TEXT,
    text TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE INDEX IF NOT EXISTS idx_companies_user_id ON companies(user_id);
  CREATE INDEX IF NOT EXISTS idx_vacancies_user_id ON vacancies(user_id);
  CREATE INDEX IF NOT EXISTS idx_applications_user_id ON applications(user_id);
`;

const postgresSchema = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS companies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    city TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS vacancies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    salary REAL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS applications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    salary REAL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Pendente',
    platform TEXT,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resume_snapshot TEXT,
    cover_letter_snapshot TEXT,
    fit_score INTEGER
  );

  CREATE TABLE IF NOT EXISTS candidate_documents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_type TEXT,
    text TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE INDEX IF NOT EXISTS idx_companies_user_id ON companies(user_id);
  CREATE INDEX IF NOT EXISTS idx_vacancies_user_id ON vacancies(user_id);
  CREATE INDEX IF NOT EXISTS idx_applications_user_id ON applications(user_id);
`;

if (isPostgres) {
  const { Pool } = require("pg");
  const databaseUrl = new URL(env.db.connectionString);
  databaseUrl.searchParams.delete("sslmode");
  pool = new Pool({
    connectionString: databaseUrl.toString(),
    ssl: { rejectUnauthorized: true },
    max: 5,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 10000
  });
  db = pool;
} else {
  const sqlitePath = env.db.file || path.join(dbDir, "jobhunter.db");
  fs.mkdirSync(path.dirname(sqlitePath), { recursive: true });
  db = new Database(sqlitePath);
  db.pragma("journal_mode = WAL");
  db.exec(sqliteSchema);

  const applicationColumns = new Set(
    db.prepare("PRAGMA table_info(applications)").all().map((column) => column.name)
  );
  for (const [column, definition] of [
    ["resume_snapshot", "TEXT"],
    ["cover_letter_snapshot", "TEXT"],
    ["fit_score", "INTEGER"]
  ]) {
    if (!applicationColumns.has(column)) {
      db.exec(`ALTER TABLE applications ADD COLUMN ${column} ${definition}`);
    }
  }
}

function normalizeParams(params) {
  if (params === undefined || params === null) return [];
  return Array.isArray(params) ? params : [params];
}

function toPostgresQuery(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

module.exports = {
  db,
  client: env.db.client,
  async initialize() {
    if (isPostgres) {
      await pool.query(postgresSchema);
      await pool.query("ALTER TABLE applications ADD COLUMN IF NOT EXISTS resume_snapshot TEXT");
      await pool.query("ALTER TABLE applications ADD COLUMN IF NOT EXISTS cover_letter_snapshot TEXT");
      await pool.query("ALTER TABLE applications ADD COLUMN IF NOT EXISTS fit_score INTEGER");
    }
    return db;
  },
  async run(sql, params = []) {
    const values = normalizeParams(params);
    if (!isPostgres) return db.prepare(sql).run(...values);

    const query = toPostgresQuery(sql);
    const insertQuery = /^\s*INSERT\b/i.test(query) && !/\bRETURNING\b/i.test(query)
      ? `${query.trim().replace(/;$/, "")} RETURNING id`
      : query;
    const result = await pool.query(insertQuery, values);
    return {
      lastInsertRowid: result.rows[0]?.id,
      changes: result.rowCount
    };
  },
  async get(sql, params = []) {
    const values = normalizeParams(params);
    if (!isPostgres) return db.prepare(sql).get(...values);
    const query = toPostgresQuery(sql);
    const result = await pool.query(query, values);
    return result.rows[0];
  },
  async all(sql, params = []) {
    const values = normalizeParams(params);
    if (!isPostgres) return db.prepare(sql).all(...values);
    const query = toPostgresQuery(sql);
    const result = await pool.query(query, values);
    return result.rows;
  },
  async exec(sql) {
    if (!isPostgres) return db.exec(sql);
    return pool.query(sql);
  },
  async close() {
    if (isPostgres) return pool.end();
    return db.close();
  }
};
